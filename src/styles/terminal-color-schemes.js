// 获取所有可用的配色方案
export function getAllColorSchemes() {
  return Object.entries(terminalColorSchemes).map(([key, value]) => ({
    id: key,
    name: value.name
  }))
}

// 根据当前主题获取配色
export function getColorScheme(schemeId, theme) {
  const scheme = terminalColorSchemes[schemeId]
  if (!scheme) return terminalColorSchemes.default[theme]
  return scheme[theme]
}
